-- FIXES 2026-07-20 (2): в ветке «есть в наличии» руководитель отдела НИЧЕГО не
-- согласует — ему уходит только уведомление (решение владельца). Шаг
-- «Руководитель отдела — выдача со склада» (добавлен в 0037) выключается:
-- движок пропускает disabled-шаги, после «есть в наличии» склад сразу выдаёт
-- («Склад — выдача в отдел»), заявка закрывается. Уведомление руководителю
-- отдела шлёт слой действий (routes). Шаг именно ВЫКЛЮЧАЕТСЯ, а не удаляется:
-- на него могут ссылаться исторические approvals (FK RESTRICT) — история
-- согласований неприкосновенна.
UPDATE workflow_steps
SET enabled = false
WHERE step_name = 'Руководитель отдела — выдача со склада'
  AND step_kind = 'approval'
  AND condition_rule @> '{"inStock": true}'::jsonb;
